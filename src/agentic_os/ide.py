def _colorize(text: str, color: str) -> str:
    if sys.stdout.isatty() or os.getenv("TERM") or os.getenv("COLORTERM"):
        return f"{color}{text}{COLOR_RESET}"
    return text


def list_targets() -> Dict[str, Dict[str, str]]:
    """Returns metadata for all supported IDE integration targets."""
    return IDE_TARGETS.copy()


def print_target_list() -> None:
    """Prints the available IDE integration targets in a clean ASCII table."""
    print(_colorize("\n=======================================================", COLOR_CYAN))
    print(_colorize("         AgenticOS Multi-Agent & IDE Targets           ", COLOR_BOLD + COLOR_CYAN))
    print(_colorize("=======================================================\n", COLOR_CYAN))
    for key, info in IDE_TARGETS.items():
        print(f"  * {_colorize(key, COLOR_BOLD + COLOR_GREEN):<16} {info['name']:<28} [{info['mode']}]")
        print(f"    File: {info['primary_file']}")
        print(f"    Desc: {_colorize(info['description'], COLOR_GRAY)}\n")
    print(_colorize("To configure an IDE target, run:", COLOR_GRAY))
    print(_colorize("  agentic-os ide configure --target <target>\n", COLOR_CYAN))


